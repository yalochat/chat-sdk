// The staged proto tree holds SdkMessageOuterClass.java. Registering it as a kotlin srcDir only
// puts it on the Kotlin java-source-roots path (enough to resolve against, but no .class is
// emitted), so it also has to be handed to javac or the compiled Kotlin wrappers would reference
// a class that is missing from the AAR.
androidComponents {
    onVariants { variant ->
        variant.sources.java?.addGeneratedSourceDirectory(syncProtoSources) { it.outputDir }
    }
}

