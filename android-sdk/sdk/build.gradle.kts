// The KMP Android library plugin has no BuildConfig and no build variants, so the dev-only
// toggles previously exposed as buildConfigField are generated as a plain Kotlin object.
val useFakeRepo = localProps.getProperty("yalo.useFakeRepository", "false")
    .trim().toBooleanStrictOrNull() ?: false
val transport = localProps.getProperty("yalo.transport", "WEBSOCKET").trim().uppercase()

val generateSdkBuildConfig = tasks.register("generateSdkBuildConfig") {
    val outputDir = layout.buildDirectory.dir("generated/sdkBuildConfig/kotlin")
    inputs.property("useFakeRepository", useFakeRepo)
    inputs.property("transport", transport)
    outputs.dir(outputDir)
    doLast {
        val target = outputDir.get().dir("com/yalo/chat/sdk").asFile
        target.mkdirs()
        target.resolve("SdkBuildConfig.kt").writeText(
            """
            // Copyright (c) Yalochat, Inc. All rights reserved.
            // Generated by the generateSdkBuildConfig Gradle task. Do not edit.

            package com.yalo.chat.sdk

            internal object SdkBuildConfig {
                const val USE_FAKE_REPOSITORY: Boolean = $useFakeRepo
                const val TRANSPORT: String = "$transport"
            }

            """.trimIndent()
        )
    }
}

// Stages proto/kotlin/ into the build directory, dropping the wrappers that cannot compile.
//
// GetCommandsRequestKt / GetCommandsResponseKt were generated from a newer proto revision than
// the committed SdkMessageOuterClass.java: they reference GetCommandsRequest and
// GetCommandsResponse, which that Java outer class does not declare. Compiling them fails
// outright, and their broken timestampOrNull extensions also make timestampOrNull ambiguous in
// every other proto file. The SDK does not use these wrappers; the raw Java accessors in
// SdkMessageOuterClass are sufficient. Regenerating proto/ would remove the need for this.
abstract class StageProtoSources : DefaultTask() {
    @get:InputDirectory
    abstract val source: DirectoryProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @get:Inject
    abstract val fs: FileSystemOperations

    @TaskAction
    fun stage() {
        fs.sync {
            from(source)
            into(outputDir)
            exclude("**/GetCommandsRequestKt.kt", "**/GetCommandsResponseKt.kt")
        }
    }
}

val syncProtoSources = tasks.register<StageProtoSources>("syncProtoSources") {
    source.set(rootProject.file("../proto/kotlin"))
    outputDir.set(layout.buildDirectory.dir("generated/protoSources"))
}

